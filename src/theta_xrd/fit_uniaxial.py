"""
Ramanujan-theta line positions and (a, c) refinement for TETRAGONAL and
HEXAGONAL / TRIGONAL crystals
=========================================================================

  tetragonal:  1/d^2 = (h^2 + k^2) / a^2 + l^2 / c^2
               h^2 + k^2  is generated by Ramanujan's  phi(q)^2   (sums of two squares)
  hexagonal:   1/d^2 = 4 (h^2 + hk + k^2) / (3 a^2) + l^2 / c^2
               h^2+hk+k^2 is generated by the Borwein cubic theta  a(q)
  l^2 in both cases comes from Ramanujan's phi(q).

Each allowed line is a pair (A, L) with nonzero coefficient in the product
of the two theta series. Lattice centering:
  I (tetragonal body-centred): h+k+l even  <=>  A + L even  (h = h^2 mod 2)
  R (rhombohedral, hexagonal axes, obverse): -h + k + l = 3n  (checked on the
    (h, k, l) representatives of each (A, L) shell)
Space-group glide/screw absences are NOT applied; the fit scores how many
MEASURED peaks are explained, so extra predicted lines do not count against it.

This is a cell REFINEMENT: the search window is a few percent around a
nominal cell, as in standard practice (ab-initio indexing is out of scope).

Author: Wilmer Gaspar Espinoza Castillo
"""

from dataclasses import dataclass, field
from typing import List, Optional, Sequence, Tuple

import numpy as np

from src.theta_xrd.ramanujan_xrd import phi_series, borwein_a_series, CU_KA1


def _phi2(M):
    p = phi_series(M)
    return np.convolve(p, p)[: M + 1]


def line_shells(system: str, centering: str, a_max_index: int, l_max: int) -> List[Tuple[int, int]]:
    """(A, L) pairs allowed by the theta series and the lattice centering."""
    if system == "tetragonal":
        Acoef = _phi2(a_max_index)
    elif system == "hexagonal":
        Acoef = borwein_a_series(a_max_index)
    else:
        raise ValueError("system must be 'tetragonal' or 'hexagonal'")
    Lcoef = phi_series(l_max * l_max)
    shells = []
    r = int(np.sqrt(a_max_index)) + 2
    for A in range(a_max_index + 1):
        if Acoef[A] == 0:
            continue
        for l in range(0, l_max + 1):
            L = l * l
            if Lcoef[L] == 0 or (A == 0 and L == 0):
                continue
            if centering == "I" and (A + L) % 2:
                continue
            if centering == "R":
                ok = False
                for h in range(-r, r + 1):
                    for k in range(-r, r + 1):
                        if h * h + h * k + k * k != A:
                            continue
                        if (-h + k + l) % 3 == 0 or (-h + k - l) % 3 == 0:
                            ok = True
                            break
                    if ok:
                        break
                if not ok:
                    continue
            shells.append((A, L))
    return shells


def inv_d2(shells, a, c, system):
    A = np.array([s[0] for s in shells], float)
    L = np.array([s[1] for s in shells], float)
    fa = A / a ** 2 if system == "tetragonal" else 4 * A / (3 * a ** 2)
    return fa + L / c ** 2


def two_theta(shells, a, c, system, wavelength):
    s = wavelength * np.sqrt(inv_d2(shells, a, c, system)) / 2
    return np.degrees(2 * np.arcsin(np.clip(s, 0, 1)))


@dataclass
class UniaxialFit:
    a: float
    c: float
    zero_shift: float
    matched: int
    n_measured: int
    rms_deg: float
    unmatched: List[float] = field(default_factory=list)


def fit_uniaxial(peaks_2theta: Sequence[float], system: str, centering: str,
                 a0: float, c0: float, window: float = 0.03,
                 wavelength: float = CU_KA1, tol_deg: float = 0.08,
                 weights: Optional[Sequence[float]] = None, steps: int = 61) -> UniaxialFit:
    """Grid search over (a, c) within +/- window of (a0, c0), then Gauss-Newton on (a, c, zero)."""
    obs = np.asarray(peaks_2theta, float)
    w = np.ones_like(obs) if weights is None else np.asarray(weights, float)
    tt_max = obs.max() + 1
    d_min = wavelength / (2 * np.sin(np.radians(tt_max / 2)))
    amax = a0 * (1 + window)
    cmax = c0 * (1 + window)
    A_max = int((amax / d_min) ** 2 * (1.0 if system == "tetragonal" else 0.75)) + 2
    l_max = int(cmax / d_min) + 1
    shells = line_shells(system, centering, A_max, l_max)

    def evaluate(a, c, z=None):
        calc = two_theta(shells, a, c, system, wavelength)
        calc = calc[calc <= tt_max]
        if calc.size == 0:
            return -1, 0.0, None
        if z is None:
            # estimate the zero shift from the nearest UNshifted lines
            d0 = obs[:, None] - calc[None, :]
            dd0 = d0[np.arange(len(obs)), np.argmin(np.abs(d0), axis=1)]
            near = np.abs(dd0) < 3 * tol_deg
            z = float(np.median(dd0[near])) if near.any() else 0.0
        # then match every peak to the nearest SHIFTED line (fix, Oct 21: matching
        # before shifting mis-assigned peaks when |z| is comparable to the line spacing)
        d = obs[:, None] - (calc[None, :] + z)
        j = np.argmin(np.abs(d), axis=1)
        dd = d[np.arange(len(obs)), j]
        hit = np.abs(dd) <= tol_deg
        return float(np.sum(w[hit])) - 1e-3 * float(np.sum(np.abs(dd[hit]))), z, (calc, j, hit)

    best = None
    for a in np.linspace(a0 * (1 - window), amax, steps):
        for c in np.linspace(c0 * (1 - window), cmax, steps):
            s, z, _ = evaluate(a, c)
            if best is None or s > best[0]:
                best = (s, a, c, z)
    _, a, c, z = best

    # local fine search, then Gauss-Newton on matched pairs
    for span in (0.004, 0.001):
        local = None
        for da in np.linspace(-span, span, 21):
            for dc in np.linspace(-span, span, 21):
                s, zz, _ = evaluate(a * (1 + da), c * (1 + dc))
                if local is None or s > local[0]:
                    local = (s, a * (1 + da), c * (1 + dc), zz)
        _, a, c, z = local

    for _ in range(20):
        _, _, info = evaluate(a, c, z)
        calc, j, hit = info
        if hit.sum() < 3:
            break
        sub = [shells[k] for k in range(len(shells))]
        allc = two_theta(sub, a, c, system, wavelength)
        idx_in = np.where(allc <= tt_max)[0]
        S = [sub[k] for k in idx_in[j[hit]]]
        o = obs[hit]
        f = two_theta(S, a, c, system, wavelength) + z - o
        ea, ec = 1e-5 * a, 1e-5 * c
        Ja = (two_theta(S, a + ea, c, system, wavelength) - two_theta(S, a, c, system, wavelength)) / ea
        Jc = (two_theta(S, a, c + ec, system, wavelength) - two_theta(S, a, c, system, wavelength)) / ec
        J = np.column_stack([Ja, Jc, np.ones_like(Ja)])
        step, *_ = np.linalg.lstsq(J, -f, rcond=None)
        a, c, z = a + step[0], c + step[1], z + step[2]
        if np.all(np.abs(step) < [1e-7, 1e-7, 1e-6]):
            break

    _, _, (calc, j, hit) = evaluate(a, c, z)
    dd = obs - (calc[j] + z)
    return UniaxialFit(a=float(a), c=float(c), zero_shift=float(z), matched=int(hit.sum()),
                       n_measured=len(obs),
                       rms_deg=float(np.sqrt(np.mean(dd[hit] ** 2))) if hit.any() else float("nan"),
                       unmatched=[float(x) for x in obs[~hit]])
