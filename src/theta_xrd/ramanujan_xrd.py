"""
Ramanujan Theta Functions -> X-ray Powder Diffraction Patterns
==============================================================

Core idea
---------
In a powder XRD pattern, a reflection (h,k,l) of a cubic crystal with lattice
parameter a appears at

    1/d^2 = N / a^2,      N = h^2 + k^2 + l^2,     lambda = 2 d sin(theta)

so every peak position is fixed by an integer N, and the number of
reflections that coincide at that position (the multiplicity) is the number
of ways to write N as h^2 + k^2 + l^2.

That count is exactly the coefficient of q^N in a product of Ramanujan's
theta functions. Using Ramanujan's notation

    phi(q) = sum_{n=-inf..inf} q^(n^2)          (= f(q, q))
    psi(q) = sum_{n=0..inf}   q^(n(n+1)/2)       (= f(q, q^3))

the generating functions ("lattice theta series") of the reciprocal lattices
of the three cubic Bravais lattices are

    primitive  (P):  Theta_P(q) = phi(q)^3
    body-ctr.  (I):  Theta_I(q) = [phi(q)^3 + phi(-q)^3] / 2      (h+k+l even)
    face-ctr.  (F):  Theta_F(q) = phi(q^4)^3 + 8 q^3 psi(q^8)^3   (h,k,l all even or all odd)

For hexagonal / trigonal crystals (quartz, calcite in hexagonal axes)

    1/d^2 = 4 (h^2 + hk + k^2) / (3 a^2) + l^2 / c^2

and h^2 + hk + k^2 is generated by the Borwein cubic theta function
a(q) = sum q^(m^2 + mn + n^2), from Ramanujan's theory of elliptic functions
to alternative bases (signature 3). The l-part is phi(q) again.

Consequence you can see in real data: a primitive cubic pattern has NO line
at N = 7, 15, 23, 28, ... because, by Legendre's three-square theorem,
numbers of the form 4^a (8b + 7) are never a sum of three squares, so their
coefficient in phi(q)^3 is zero.

Scope / limitations
-------------------
The theta series gives peak POSITIONS and MULTIPLICITIES allowed by the
lattice. Extra absences caused by the atoms in the cell (e.g. diamond-type
Si, where 200 vanishes) and peak INTENSITIES need the structure factor;
`structure_factor_filter` handles absences for a given basis.

Author: Wilmer Gaspar Espinoza Castillo
"""

from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

CU_KA1 = 1.5406  # Angstrom


# ─────────────────────────────────────────────────────────────
# Power series (integer coefficient arrays, index = exponent)
# ─────────────────────────────────────────────────────────────

def phi_series(M: int) -> np.ndarray:
    """Ramanujan phi(q) = sum_{n in Z} q^(n^2), coefficients up to q^M."""
    c = np.zeros(M + 1, dtype=np.int64)
    n = 0
    while n * n <= M:
        c[n * n] += 1 if n == 0 else 2
        n += 1
    return c


def psi_series(M: int) -> np.ndarray:
    """Ramanujan psi(q) = sum_{n>=0} q^(n(n+1)/2), coefficients up to q^M."""
    c = np.zeros(M + 1, dtype=np.int64)
    n = 0
    while n * (n + 1) // 2 <= M:
        c[n * (n + 1) // 2] += 1
        n += 1
    return c


def borwein_a_series(M: int) -> np.ndarray:
    """Borwein cubic theta a(q) = sum_{m,n in Z} q^(m^2 + m n + n^2)."""
    c = np.zeros(M + 1, dtype=np.int64)
    r = int(np.sqrt(4 * M / 3)) + 2
    for m in range(-r, r + 1):
        for n in range(-r, r + 1):
            e = m * m + m * n + n * n
            if e <= M:
                c[e] += 1
    return c


def mul(a: np.ndarray, b: np.ndarray, M: int) -> np.ndarray:
    return np.convolve(a, b)[: M + 1]


def subs_power(a: np.ndarray, k: int, M: int) -> np.ndarray:
    """a(q) -> a(q^k)."""
    out = np.zeros(M + 1, dtype=np.int64)
    for e, v in enumerate(a):
        if e * k <= M:
            out[e * k] += v
    return out


def subs_neg(a: np.ndarray) -> np.ndarray:
    """a(q) -> a(-q)."""
    return a * np.where(np.arange(len(a)) % 2 == 0, 1, -1)


def shift(a: np.ndarray, s: int, M: int) -> np.ndarray:
    """multiply by q^s."""
    out = np.zeros(M + 1, dtype=np.int64)
    out[s:] = a[: M + 1 - s]
    return out


def theta_cubic(lattice: str, M: int) -> np.ndarray:
    """Lattice theta series of the reciprocal-lattice condition for P, I or F cubic."""
    lattice = lattice.upper()
    if lattice == "P":
        p = phi_series(M)
        return mul(mul(p, p, M), p, M)
    if lattice == "I":
        p = phi_series(M)
        p3 = mul(mul(p, p, M), p, M)
        pn = subs_neg(p)
        pn3 = mul(mul(pn, pn, M), pn, M)
        return (p3 + pn3) // 2
    if lattice == "F":
        p4 = subs_power(phi_series(M), 4, M)
        s8 = subs_power(psi_series(M), 8, M)
        even = mul(mul(p4, p4, M), p4, M)
        odd = 8 * shift(mul(mul(s8, s8, M), s8, M), 3, M)
        return even + odd
    raise ValueError("lattice must be 'P', 'I' or 'F'")


def brute_force_cubic(lattice: str, M: int) -> np.ndarray:
    """Direct enumeration of (h,k,l) - used only to verify the theta identities."""
    c = np.zeros(M + 1, dtype=np.int64)
    r = int(np.sqrt(M)) + 1
    for h in range(-r, r + 1):
        for k in range(-r, r + 1):
            for l in range(-r, r + 1):
                N = h * h + k * k + l * l
                if N > M:
                    continue
                if lattice == "I" and (h + k + l) % 2:
                    continue
                if lattice == "F" and len({h % 2, k % 2, l % 2}) > 1:
                    continue
                c[N] += 1
    return c


# ─────────────────────────────────────────────────────────────
# From theta coefficients to a powder pattern
# ─────────────────────────────────────────────────────────────

@dataclass
class Line:
    two_theta: float
    d: float
    multiplicity: int
    label: str          # N for cubic, "A,l2" for hexagonal


def _two_theta(d, wavelength):
    s = wavelength / (2 * d)
    return float(np.degrees(2 * np.arcsin(s))) if s <= 1 else None


def cubic_pattern(a: float, lattice: str = "P", wavelength: float = CU_KA1,
                  two_theta_max: float = 90.0,
                  allowed_N: Optional[set] = None) -> List[Line]:
    d_min = wavelength / (2 * np.sin(np.radians(two_theta_max / 2)))
    M = int((a / d_min) ** 2) + 1
    theta = theta_cubic(lattice, M)
    lines = []
    for N in range(1, M + 1):
        if theta[N] == 0 or (allowed_N is not None and N not in allowed_N):
            continue
        d = a / np.sqrt(N)
        tt = _two_theta(d, wavelength)
        if tt is not None and tt <= two_theta_max:
            lines.append(Line(tt, d, int(theta[N]), f"N={N}"))
    return lines


def hexagonal_pattern(a: float, c: float, wavelength: float = CU_KA1,
                      two_theta_max: float = 60.0, l_rule=None) -> List[Line]:
    """
    Positions from Borwein a(q) (in-plane) x phi(q) (l). Lines with equal d merge.
    l_rule(A, l) -> bool lets you apply a known extinction rule (optional).
    """
    d_min = wavelength / (2 * np.sin(np.radians(two_theta_max / 2)))
    MA = int(3 * a * a / (4 * d_min ** 2)) + 1
    ML = int((c / d_min) ** 2) + 1
    A_coef = borwein_a_series(MA)
    L_coef = phi_series(ML)
    merged: Dict[float, Line] = {}
    for A in range(MA + 1):
        if A_coef[A] == 0:
            continue
        for l2 in range(ML + 1):
            if L_coef[l2] == 0 or (A == 0 and l2 == 0):
                continue
            if l_rule is not None and not l_rule(A, int(round(np.sqrt(l2)))):
                continue
            inv_d2 = 4 * A / (3 * a * a) + l2 / (c * c)
            d = 1 / np.sqrt(inv_d2)
            tt = _two_theta(d, wavelength)
            if tt is None or tt > two_theta_max:
                continue
            key = round(tt, 3)
            mult = int(A_coef[A] * L_coef[l2])
            if key in merged:
                merged[key].multiplicity += mult
                merged[key].label += f"; A={A},l={int(round(np.sqrt(l2)))}"
            else:
                merged[key] = Line(tt, d, mult, f"A={A},l={int(round(np.sqrt(l2)))}")
    return sorted(merged.values(), key=lambda x: x.two_theta)


# ─────────────────────────────────────────────────────────────
# Independent check: structure factor of an atomic basis
# ─────────────────────────────────────────────────────────────

def structure_factor_allowed_N(basis: Sequence[Tuple[float, float, float, float]],
                               M: int, tol: float = 1e-6) -> set:
    """
    Cubic cell: return the set of N = h^2+k^2+l^2 having at least one (h,k,l)
    with |F|^2 > tol. basis = [(x, y, z, weight), ...] in fractional coords.
    Weights approximate scattering power (e.g. atomic number).
    """
    allowed = set()
    r = int(np.sqrt(M)) + 1
    xyz = np.array([b[:3] for b in basis])
    w = np.array([b[3] for b in basis])
    for h in range(-r, r + 1):
        for k in range(-r, r + 1):
            for l in range(-r, r + 1):
                N = h * h + k * k + l * l
                if N == 0 or N > M or N in allowed:
                    continue
                F = np.sum(w * np.exp(2j * np.pi * (xyz @ np.array([h, k, l]))))
                if abs(F) ** 2 > tol:
                    allowed.add(N)
    return allowed


# ─────────────────────────────────────────────────────────────
# Full powder profile for a cubic phase (positions from theta, intensities from |F|^2)
# ─────────────────────────────────────────────────────────────

def cubic_profile(grid_2theta, a, lattice, basis, wavelength=CU_KA1, fwhm=0.15,
                  b_factor=0.0, zero_shift=0.0):
    """
    Simulated powder profile on a 2-theta grid.

    Lines: every N with nonzero coefficient in the Ramanujan lattice theta series.
    Intensity of line N: sum over all (h,k,l) with h^2+k^2+l^2 = N of |F_hkl|^2
    (so the multiplicity is built in), times the Lorentz-polarization factor.
    basis = [(x, y, z, Z), ...]; scattering factor f = Z * exp(-b_factor * s^2),
    s = sin(theta)/lambda. b_factor = 0 means constant f (library model).
    Peaks are Gaussian with the given FWHM (deg).
    """
    grid = np.asarray(grid_2theta, float)
    tt_max = grid.max() + 1
    d_min = wavelength / (2 * np.sin(np.radians(tt_max / 2)))
    M = int((a / d_min) ** 2) + 1
    theta = theta_cubic(lattice, M)
    xyz = np.array([b[:3] for b in basis])
    Z = np.array([b[3] for b in basis], float)
    r = int(np.sqrt(M)) + 1
    hkl_by_N: Dict[int, list] = {}
    for h in range(-r, r + 1):
        for k in range(-r, r + 1):
            for l in range(-r, r + 1):
                N = h * h + k * k + l * l
                if 0 < N <= M and theta[N] > 0:
                    hkl_by_N.setdefault(N, []).append((h, k, l))
    y = np.zeros_like(grid)
    sig = fwhm / 2.3548
    for N, hkls in hkl_by_N.items():
        d = a / np.sqrt(N)
        tt = _two_theta(d, wavelength)
        if tt is None:
            continue
        th = np.radians(tt / 2)
        s = np.sin(th) / wavelength
        f = Z * np.exp(-b_factor * s * s)
        H = np.array(hkls)
        F = (f[None, :] * np.exp(2j * np.pi * H @ xyz.T)).sum(axis=1)
        I = float(np.sum(np.abs(F) ** 2))
        if I < 1e-6:
            continue
        lp = (1 + np.cos(2 * th) ** 2) / (np.sin(th) ** 2 * np.cos(th))
        y += I * lp * np.exp(-0.5 * ((grid - tt - zero_shift) / sig) ** 2)
    return y
